#include <iostream>
using namespace std;

// ПРОТОТИП функції f (це просто "анонс" для компілятора).
// n     - число, з яким працюємо
// level - на якому ми зараз рівні рекурсії (1, 2, 3...)
// depth - глибина рекурсії; це посилання (&), тому функція
//         може змінити depth, і зміна буде видна в main
int f(int n, int level, int& depth);

int main()
{
    int p, q;
    cout << "Enter p and q (p <= q): ";
    cin >> p >> q;                // вводимо межі: від p до q

    int sum = 0;                  // тут буде сума S(p, q), спочатку 0
    int maxDepth = 0;             // тут буде найбільша глибина, спочатку 0

    // Беремо по черзі кожне число i від p до q
    for (int i = p; i <= q; i++)
    {
        int depth = 0;            // глибину для нового числа починаємо з 0
        cout << "i = " << i << endl;

        // Викликаємо f для числа i. Рівень ставимо 1 (це перший виклик).
        int value = f(i, 1, depth);

        // Показуємо результат f(i) і глибину рекурсії
        cout << "  f(" << i << ") = " << value
            << ", recursion depth = " << depth << endl;

        sum = sum + value;        // додаємо f(i) до суми

        if (depth > maxDepth)     // якщо ця глибина більша за найбільшу,
            maxDepth = depth;     // запам'ятовуємо її
    }

    cout << "S(" << p << ", " << q << ") = " << sum << endl;
    cout << "Max recursion depth = " << maxDepth << endl;

    return 0;
}

// САМА ФУНКЦІЯ f. Вона знаходить останню ненульову цифру числа.
int f(int n, int level, int& depth)
{
    // Якщо поточний рівень більший за глибину, яку ми знаємо,
    // то записуємо новий рівень як глибину
    if (level > depth)
        depth = level;

    // Показуємо, на якому ми рівні і яке зараз число
    cout << "  level " << level << ": f(" << n << ")" << endl;

    // КРОК 1 (кінець рекурсії): число стало 0 - повертаємо 0
    if (n == 0)
        return 0;

    // КРОК 2 (кінець рекурсії): остання цифра НЕ нуль -
    // це і є відповідь, повертаємо її
    if (n % 10 != 0)
        return n % 10;

    // КРОК 3 (рекурсія): остання цифра нуль, тому відкидаємо її
    // (ділимо на 10) і викликаємо цю ж функцію ще раз.
    // Рівень збільшуємо на 1.
    return f(n / 10, level + 1, depth);
}